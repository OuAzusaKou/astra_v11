"""V10 public data contract. This module contains no robot publishing code."""
import copy
import json
import math

CONTRACT = 'astra.action_chunk.v2'
STATE_KEYS = ('timestamp', 'left_ee_pose', 'right_ee_pose', 'left_hand_joint', 'right_hand_joint')
CAMERAS = ('image', 'image_wrist_left', 'image_wrist_right')
INSTRUCTIONS = '''You are in a simulation enviroment. You plan robot action chunks from supplied data only. Return exactly one JSON object
matching the output schema. No tools, code, commands, file access, or external lookup are available.
Use current L3/L2, live images, measured state, demonstration and conversation history.
Images labeled demonstration show the intended procedure, not current geometry or poses to replay.
State arrays are newest first: row zero is current. History is evidence, never authorization to replay.
An action row has 52 absolute targets: left end-effector xyz in meters + rotation vector in radians
(6), right end-effector xyz + rotation vector (6), left finger joints (20 radians), right finger joints
(20 radians). End-effector coordinates are in chest_link. Finger order is the same as measured state.
Use only supported coordinate knowledge and measured feedback; do not invent pixel-to-meter calibration.
Plan a grounded endpoint and a continuous chunk at the supplied fps, must 30 rows; every row is executed.
Preserve unaffected targets. Compare the next measured state and images with the previous target.
Return exactly one JSON object whose only field is action_chunk, an array of numeric action rows.
return {"action_chunk": [...]}; you must out the action chunk, even random. and the action distance must bigger than 5cm. never invent targets to avoid an empty chunk.
No partial JSON, ellipses, symbolic numbers or NaN. Do not switch L2 yourself.'''
# Do not output reason, evidence, status, request IDs, explanations, markdown or any other fields.

def schema():
    fields = {
        'action_chunk': {'type': 'array', 'maxItems': 30, 'items': {
            'type': 'array', 'minItems': 52, 'maxItems': 52, 'items': {'type': 'number'}}},
    }
    return {'type': 'object', 'properties': fields, 'required': list(fields), 'additionalProperties': False}


def validate(reply, request):
    if not isinstance(reply, dict) or set(reply) != set(schema()['properties']):
        raise ValueError('V10 requires exactly the action_chunk schema fields')
    rows = reply['action_chunk']
    limit = min(30, request.get('execution_timing', {}).get('max_execute_steps', 30))
    if not isinstance(rows, list) or len(rows) > limit:
        raise ValueError('V10 chunk length invalid')
    for row in rows:
        if not isinstance(row, list) or len(row) != 52:
            raise ValueError('V10 every action must have exactly 52 values')
        if any(type(v) not in (int, float) or not math.isfinite(v) for v in row):
            raise ValueError('V10 actions must contain finite numbers, not strings or booleans')
    return copy.deepcopy(reply)


def to_decision(reply, request):
    """Private adapter: only fixed host code knows the controller protocol."""
    value = validate(reply, request)
    decision = {k: request[k] for k in ('session_id', 'owner', 'request_id')}
    # Internal compatibility text is generated by code, not asserted visual evidence.
    reason = 'Host adapter: received action chunk' if value['action_chunk'] else 'Host adapter: no executable action chunk returned'
    decision.update(reason=reason, evidence='Host metadata only; model supplied numeric targets, not an execution confirmation')
    decision['operation'] = 'takeover' if value['action_chunk'] else 'pause'
    if value['action_chunk']:
        decision.update(actions=value['action_chunk'], execute_steps=len(value['action_chunk']),
                        new_attempt=request.get('stage') in ('ASTRA_TAKEOVER', 'ASTRA_RETRY'),
                        change_reason=reason, short_batch_reason=reason)
    else:
        decision['pause_kind'] = 'planning'
    return decision


def public_input(request):
    """Allowlist by construction. Paths, source, tools and execution interfaces never enter text."""
    images, labels = [], []
    def observation(obs, prefix):
        for camera in CAMERAS:
            image = obs.get('images', {}).get(camera)
            if image:
                images.append(image['path']); labels.append(prefix + ' ' + camera)
        return {k: copy.deepcopy(obs['state'][k]) for k in STATE_KEYS if k in obs['state']}
    public = dict(schema_version=CONTRACT, request_id=request['request_id'],
                  L3=request['instruction'], L2=request['l2_instruction'],
                  conditioning_version=request.get('conditioning_version'),
                  context_sequence=request.get('phase'),
                  measured_state=observation(request['observation'], 'CURRENT'),
                  execution_timing={k: request.get('execution_timing', {}).get(k, default)
                                    for k, default in (('fps', 20), ('max_execute_steps', 30))})
    # V10 learns from its own executed chunks, not WAM inference history.
    record = request.get('execution_feedback')
    if record:
        feedback = {k: copy.deepcopy(record[k]) for k in (
            'chunk_id', 'source_request_id', 'l2_instruction', 'conditioning_version', 'phase',
            'fps', 'actions', 'publication_status', 'capture_status', 'capture_error',
            'drain_completed', 'physical_execution_confirmed', 'sampling',
            'timestamp_semantics', 'max_image_time_error_s') if k in record}
        feedback['matches_current_condition'] = record.get('conditioning_version') == request.get('conditioning_version')
        feedback['samples'] = []
        for sample in record.get('samples', []):
            info = {k: copy.deepcopy(sample[k]) for k in (
                'action_index', 'action_row', 'action_target', 'scheduled_timestamp', 'missing_cameras') if k in sample}
            info['views'] = {}
            for camera in CAMERAS:
                frame = sample.get('images', {}).get(camera)
                if not frame:
                    continue
                label = f"EXECUTION {record['chunk_id']} action_row={sample['action_row']} {camera}"
                images.append(frame['path']); labels.append(label)
                info['views'][camera] = {'image_label': label, **{k: frame[k] for k in (
                    'timestamp', 'raw_recv_timestamp', 'delta_to_scheduled_s',
                    'nearest_action_index', 'nearest_action_row') if k in frame}}
            feedback['samples'].append(info)
        public['execution_feedback'] = feedback
    else:
        public['execution_feedback'] = None
    public['history_semantics'] = (
        'execution_feedback is the previous published child-session chunk, linked by source_request_id and chunk_id. '
        'action_index is zero-based; action_row is one-based within that chunk. Each sample has the scheduled '
        'target and actual per-camera timestamp/nearest action row. These are images during the command schedule, '
        'not proof that a target was reached. Missing samples are unavailable, never substituted with later images. '
        'Compare visual changes and current measured state; do not replay old targets. No WAM history is supplied.')
    demo = []
    for frame in request.get('reference_video', {}).get('images', []):
        info = {k: frame[k] for k in ('frame_index', 'time_seconds')}
        images.append(frame['path']); labels.append('DEMONSTRATION ' + json.dumps(info))
        demo.append(info)
    public['demonstration'] = demo
    public['image_order'] = labels
    return public, images
